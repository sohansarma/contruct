import fs from 'node:fs';
import path from 'node:path';
import * as L from 'lucide-react';
const files = [];
const walk = (d) => fs.readdirSync(d).forEach((f) => { const p = path.join(d, f); fs.statSync(p).isDirectory() ? walk(p) : /\.(jsx?|js)$/.test(p) && !p.endsWith('icons.js') && files.push(p); });
walk('src');
const names = new Set(['Box']);
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/['"]([A-Z][A-Za-z0-9]*)['"]/g)) if (L[m[1]] && L[m[1]].$$typeof) names.add(m[1]);
const list = [...names].sort();
fs.writeFileSync('src/components/icons.js', `// Generated by scripts/gen-icons.mjs — explicit imports keep the bundle small.\nimport { ${list.join(', ')} } from 'lucide-react';\n\nexport default { ${list.join(', ')} };\n`);
console.log(list.length, list.join(' '));
